L = "ABCD"

def fmt(s):
    """`x` -> <code>, ```x``` -> <pre>, com o código escapado."""
    s = re.sub(r"```\n?(.*?)```", lambda m: f"<pre><code>{H.escape(m.group(1).strip(chr(10)))}</code></pre>", s, flags=re.S)
    return re.sub(r"`([^`]+)`", lambda m: f"<code>{H.escape(m.group(1))}</code>", s)

def plano(s):
    return re.sub(r"<[^>]+>", "", fmt(s))

def Q(qid, text, right, wrongs, why_right, why_wrongs, sec, lembrar=None):
    assert len(wrongs) == 3 and len(why_wrongs) == 3, qid
    for o in [right] + wrongs:
        assert not re.search(r"(todas|nenhuma) (as|das) anteriores", o, re.I), f"{qid}: opção dependente da posição"
    return dict(id=qid, text=fmt(text), right=fmt(right), wrongs=[fmt(w) for w in wrongs], wr=fmt(why_right),
                ww=[fmt(w) for w in why_wrongs], sec=S[sec], lembrar=fmt(lembrar) if lembrar else None,
                len_r=len(plano(right)), len_w=[len(plano(w)) for w in wrongs])

def montar(q, pos, topic):
    opts = q["wrongs"][:]; whys = q["ww"][:]
    opts.insert(pos, q["right"]); whys.insert(pos, q["wr"])
    ok = f'<div class="sol-ok"><b>({L[pos]}) Certa.</b> {whys[pos]}</div>'
    no = "".join(f"<li><b>({L[i]}) Errada.</b> {whys[i]}</li>" for i in range(4) if i != pos)
    exp = f'<div class="sol-title">Correção</div>{ok}<ul class="sol-no">{no}</ul>'
    nota = (f"<b>Para lembrar:</b> {q['lembrar']}<br>" if q["lembrar"] else "") + (
        f'Se a correção não chegou, lê a teoria: <a class="teoria" href="{GUIA}#{q["sec"]}" target="_blank">'
        f'📖 {TITULO[q["sec"]]}</a>')
    return [topic, q["id"], q["text"], opts, pos, exp, nota]

TOPICOS = []
def topic(slug, var, name, qs): TOPICOS.append((slug, var, name, qs))

